"""Central place for file locations and settings.

Everything can be redirected with environment variables, which is also how the
test-suite points the app at a small temporary dataset.
"""
import os
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parent.parent
PROJECT_DIR = BACKEND_DIR.parent

# Folder that holds the movie dataset and the generated search index.
DATA_DIR = Path(os.getenv("MOVIE_DATA_DIR", BACKEND_DIR / "data"))

SEED_PATH = DATA_DIR / "movies_seed.json"    # the dataset (committed)
INDEX_PATH = DATA_DIR / "faiss.index"        # generated by build_index.py
INFO_PATH = DATA_DIR / "index_info.json"     # generated: which embedder built the index
EMBEDDER_PATH = DATA_DIR / "tfidf_lsa.pkl"   # generated: only for the offline fallback

# Static website that the API serves at "/" (if the folder exists).
FRONTEND_DIR = Path(os.getenv("MOVIE_FRONTEND_DIR", PROJECT_DIR / "frontend"))

# Sentence-embedding model. all-mpnet-base-v2 is the most accurate default
# (~420 MB download); "sentence-transformers/all-MiniLM-L6-v2" is much smaller.
EMBEDDING_MODEL = os.getenv("EMBEDDING_MODEL", "sentence-transformers/all-mpnet-base-v2")

# Browser origins allowed to call the API from another address
# (comma-separated). The bundled frontend is served from the same address and
# does not need CORS at all.
CORS_ORIGINS = [
    o.strip()
    for o in os.getenv("CORS_ORIGINS", "http://localhost:5173,http://127.0.0.1:5173").split(",")
    if o.strip()
]
